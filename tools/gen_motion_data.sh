#!/bin/sh
# Regenerate crates/melee/src/ft/motion_data.rs (ftData and its motion table
# entries). Sizes and offsets are checked against 1.02 machine code in
# crates/melee/src/ft/motion.rs tests; evidence is in research/notes/actions.md.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
src="$root/reference/melee/src"
rev=$(git -C "$root/reference/melee" rev-parse --short=12 HEAD)
out="$root/crates/melee/src/ft/motion_data.rs"
# Command substitution drops the generator's trailing blank line (rustfmt clean).
body=$(python3 "$root/tools/gen_dat_structs.py" "$src/melee" "$src/sysdolphin" -- \
  ftData=FighterData Fighter_WaitAnimData=MotionData)
{
  printf '%s\n' "// @generated by tools/gen_motion_data.sh from doldecomp/melee $rev." \
    "// Do not edit by hand; regenerate." "" \
    "use crate::dat::{dat_struct, DatField, DatPtr};" ""
  printf '%s\n' "$body"
} > "$out"
